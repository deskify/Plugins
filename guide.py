def _open_guide_window(api):
    win = _state.get("window")
    if win is not None:
        try:
            if win.winfo_exists():
                win.deiconify()
                win.lift()
                win.focus_force()
                return
        except Exception:
            pass

    ctk = api["ctk"]
    app = api["app"]

    win = ctk.CTkToplevel(app)
    win.title("📖 Руководство по Deskify")
    win.geometry("960x680")
    win.minsize(820, 540)
    _state["window"] = win
    _state["ui"] = {}

    # Верхняя панель
    top = ctk.CTkFrame(win, fg_color="transparent")
    top.pack(fill="x", padx=16, pady=(14, 6))
    ctk.CTkLabel(top, text="📖 Руководство по Deskify",
                 font=ctk.CTkFont(size=20, weight="bold")).pack(side="left")

    # Кнопки справа
    def copy_section():
        text = CONTENT.get(_state["current_section"], "")
        win.clipboard_clear()
        win.clipboard_append(text)
        win.update()
        api["toast"]("Раздел скопирован в буфер", "success")

    def save_section():
        path = api["filedialog"].asksaveasfilename(
            title="Сохранить раздел",
            defaultextension=".txt",
            filetypes=[("Текст", "*.txt"), ("Все файлы", "*.*")],
            initialfile=f"deskify_guide_{_state['current_section']}.txt",
        )
        if not path:
            return
        try:
            with open(path, "w", encoding="utf-8") as f:
                f.write(CONTENT.get(_state["current_section"], ""))
            api["toast"]("Раздел сохранён", "success")
        except Exception as e:
            api["messagebox"].showerror("Ошибка", str(e))

    def open_repo():
        webbrowser.open("https://github.com/deskify/Plugins")

    ctk.CTkButton(top, text="📋 Копировать", width=130, fg_color="gray30",
                  command=copy_section).pack(side="right", padx=3)
    ctk.CTkButton(top, text="💾 Сохранить", width=130, fg_color="gray30",
                  command=save_section).pack(side="right", padx=3)
    ctk.CTkButton(top, text="🔗 Репозиторий", width=140, fg_color="gray30",
                  command=open_repo).pack(side="right", padx=3)

    # Тело: слева разделы, справа текст
    body = ctk.CTkFrame(win, fg_color="transparent")
    body.pack(fill="both", expand=True, padx=16, pady=(0, 12))

    # Оглавление
    left = ctk.CTkFrame(body, width=240)
    left.pack(side="left", fill="y", padx=(0, 8))
    left.pack_propagate(False)

    ctk.CTkLabel(left, text="СОДЕРЖАНИЕ",
                 font=ctk.CTkFont(size=11, weight="bold"),
                 text_color="gray60").pack(anchor="w", padx=10, pady=(10, 4))

    nav_frame = ctk.CTkScrollableFrame(left, fg_color="transparent")
    nav_frame.pack(fill="both", expand=True, padx=6, pady=4)

    section_buttons = {}

    # Правая панель с текстом
    right = ctk.CTkFrame(body)
    right.pack(side="right", fill="both", expand=True)

    textbox = ctk.CTkTextbox(right, wrap="word",
                              font=ctk.CTkFont(family="Consolas", size=12))
    textbox.pack(fill="both", expand=True, padx=6, pady=6)

    def show_section(key):
        _state["current_section"] = key
        content = CONTENT.get(key, "Раздел не найден.")
        textbox.configure(state="normal")
        textbox.delete("1.0", "end")
        textbox.insert("1.0", content.strip() + "\n")
        textbox.configure(state="disabled")
        textbox.yview_moveto(0)

        # подсветить активный раздел
        for k, btn in section_buttons.items():
            try:
                if k == key:
                    btn.configure(fg_color="#1f538d", text_color="white")
                else:
                    btn.configure(fg_color="transparent",
                                  text_color=("gray10", "gray90"))
            except Exception:
                pass

    for key, label in SECTIONS:
        btn = ctk.CTkButton(
            nav_frame, text=label, anchor="w",
            fg_color="transparent", hover_color="gray30",
            height=34, font=ctk.CTkFont(size=13),
            command=lambda k=key: show_section(k),
        )
        btn.pack(fill="x", pady=1)
        section_buttons[key] = btn

    # Показываем первый раздел
    show_section(_state["current_section"])

    # Подвал
    footer = ctk.CTkFrame(win, fg_color="transparent")
    footer.pack(fill="x", padx=16, pady=(0, 10))
    ctk.CTkLabel(footer,
                 text="Руководство работает офлайн. Все советы актуальны для версии 1.1.0.",
                 text_color="gray60",
                 font=ctk.CTkFont(size=11)).pack(side="left")

    def on_close():
        _state["window"] = None
        try:
            win.destroy()
        except Exception:
            pass

    win.protocol("WM_DELETE_WINDOW", on_close)


